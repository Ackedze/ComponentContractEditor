  assert.equal(await page.locator('#ruleOwnershipId').getAttribute('aria-invalid'),'true');
  assert.equal(await page.evaluate(()=>document.activeElement.id),'ruleOwnershipId');
  const g=await page.evaluate(()=>({body:document.body.scrollTop,header:document.querySelector('.app-header').getBoundingClientRect().top,workspaceBottom:document.querySelector('#workspace').getBoundingClientRect().bottom}));
