  await page.locator('#constraintSection > summary').focus();await page.keyboard.press('Space');
  assert.equal(await page.locator('#collectionMax').inputValue(),'4');
  assert.match(await page.locator('#constraintSectionSummary').textContent(),/коллекц/i);
  await page.locator('#ownershipSection > summary').click();await page.locator('#ruleOwnershipKind').selectOption('component',{force:true});
