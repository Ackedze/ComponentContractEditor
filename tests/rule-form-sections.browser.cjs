  await page.goto('file://'+path.resolve(__dirname,'../dist/ui.html'));
  await page.evaluate(session=>window.postMessage({pluginMessage:{type:'session-restored',session}},'*'),session);
  await page.locator('#anatomyTree .tree-item').first().click();await page.locator('#newRuleButton').click();
  assert.equal(await page.locator('details.rule-section').count(),4);
  for(const id of ['executionSection','ownershipSection','applicabilitySection'])assert.equal(await page.locator('#'+id).evaluate(d=>d.open),false);
  await page.locator('#applicabilitySection > summary').click();
  await page.locator('#backToRulesButton').click();await page.locator('#newRuleButton').click();
  assert.equal(await page.locator('#applicabilitySection').evaluate(d=>d.open),false,'new rule must collapse previously opened Applicability');
  await page.locator('#backToRulesButton').click();
  await page.locator('#ruleSelect').selectOption(f.manual.rules[0].id,{force:true});
  await page.locator('#applicabilitySection > summary').click();
  await page.locator('#backToRulesButton').click();
  await page.locator('#ruleSelect').selectOption(f.manual.rules[0].id,{force:true});
  assert.equal(await page.locator('#applicabilitySection').evaluate(d=>d.open),false,'opening an existing rule must collapse Applicability');
  await page.locator('#applicabilitySection > summary').click();
  assert.equal(await page.locator('#contextConditions').inputValue(),'{}','collapsing must preserve applicability values');
  await page.locator('#backToRulesButton').click();await page.locator('#newRuleButton').click();
  for(const query of ['composition.members','состав','коллекция']){
   await page.locator('#capabilityInput').fill(query);await page.locator('#capabilityInput').focus();
   assert.equal(await page.locator('#capabilityOptions button').filter({hasText:'composition.members'}).count(),1);
  }
  await page.locator('#capabilityOptions button').filter({hasText:'composition.members'}).click();
  assert.equal(await page.locator('#capabilityInput').inputValue(),'composition.members');
  await page.locator('#ruleIdInput').fill('fixture.form-sections');
  await page.locator('#constraintType').selectOption('memberCollection',{force:true});
  await page.locator('#collectionFromDependency').selectOption(f.manual.componentDependencies[0].id);
  await page.locator('#collectionAssertion').selectOption('count');
